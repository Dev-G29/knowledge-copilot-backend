package com.devgangavkar.knowledgecopilot.support;

import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.model.ChatModel;
import org.springframework.ai.chat.model.ChatResponse;
import org.springframework.ai.chat.model.Generation;
import org.springframework.ai.chat.prompt.Prompt;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Primary;
import reactor.core.publisher.Flux;

/**
 * Offline stand-in for Gemini used by {@code LocalDevApplication}: builds a Markdown answer
 * from the retrieved context and streams it word by word, so the UI can be developed
 * without an API key. Embeddings come from {@link FakeAiConfiguration}.
 */
@TestConfiguration(proxyBeanMethods = false)
public class DemoAiConfiguration {

    private static final Pattern CONTEXT_BLOCK = Pattern.compile("Document: (.+?)\\R+Content: (.+?)(?=\\R\\RDocument: |\\R</context>)", Pattern.DOTALL);
    private static final Pattern QUESTION = Pattern.compile("Question: (.+)\\s*$", Pattern.DOTALL);

    @Bean
    @Primary
    ChatModel demoChatModel() {
        return new ChatModel() {
            @Override
            public ChatResponse call(Prompt prompt) {
                return response(answerFor(prompt.getContents()));
            }

            @Override
            public Flux<ChatResponse> stream(Prompt prompt) {
                List<String> words = new ArrayList<>();
                Matcher matcher = Pattern.compile("\\S+\\s*").matcher(answerFor(prompt.getContents()));
                while (matcher.find()) {
                    words.add(matcher.group());
                }
                return Flux.fromIterable(words).delayElements(Duration.ofMillis(28)).map(this::response);
            }

            private ChatResponse response(String text) {
                return new ChatResponse(List.of(new Generation(new AssistantMessage(text))));
            }
        };
    }

    static String answerFor(String prompt) {
        Matcher question = QUESTION.matcher(prompt);
        String asked = question.find() ? question.group(1).trim() : "your question";

        StringBuilder answer = new StringBuilder()
                .append("Here's what your documents say about **").append(asked).append("**:\n\n");
        Matcher block = CONTEXT_BLOCK.matcher(prompt);
        int count = 0;
        while (block.find() && count < 3) {
            String excerpt = block.group(2).replaceAll("\\s+", " ").trim();
            if (excerpt.length() > 220) {
                excerpt = excerpt.substring(0, 217) + "...";
            }
            answer.append("- ").append(excerpt).append(" *(").append(block.group(1).trim()).append(")*\n");
            count++;
        }
        answer.append("\n> Demo mode: this answer was assembled locally from the retrieved passages, not generated by Gemini.");
        return answer.toString();
    }
}
